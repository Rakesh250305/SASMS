function Section({ section, isOpen, onToggle }) {
  const Icon = section.icon;
  const darkMode = useDarkMode().darkMode;
  return (
    <div className="border-b border-slate-50 last:border-0">
      <button
        onClick={onToggle}
        className="w-full flex items-center gap-3 py-4 text-left"
      >
        <div className={`w-8 h-8 rounded-xl flex items-center justify-center flex-shrink-0 ${section.color.bg}`}>
          <Icon size={14} className={section.color.text} />
        </div>
        <span className={`flex-1 text-sm font-bold ${darkMode ? "text-slate-300" : "text-slate-700"} `}>{section.title}</span>
        <motion.div
          animate={{ rotate: isOpen ? 180 : 0 }}
          transition={{ duration: 0.2 }}
        >
          <ChevronDown size={15} className="text-gray-400" />
        </motion.div>
      </button>

      <AnimatePresence initial={false}>
        {isOpen && (
          <motion.div
            initial={{ height: 0, opacity: 0 }}
            animate={{ height: "auto", opacity: 1 }}
            exit={{ height: 0, opacity: 0 }}
            transition={{ duration: 0.2, ease: "easeInOut" }}
            className="overflow-hidden"
          >
            <p className={`text-sm ${darkMode ? "text-gray-400" : "text-gray-500"} leading-relaxed pb-4 pr-2`}>{section.body}</p>
          </motion.div>
        )}
      </AnimatePresence>
    </div>
  );
}

